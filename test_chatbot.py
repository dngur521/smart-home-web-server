results = {"PASS": [], "FAIL": [], "ERR": []}

def test_one(question, category, must_have, must_not_have):
    try:
        r = requests.post(BASE_URL,
                          json={"message": question, "history": []},
                          timeout=90)
        if r.status_code != 200:
            return "ERR", f"HTTP {r.status_code}", ""
        reply = r.json().get("reply", "")
        if not reply:
            return "FAIL", "빈 응답", reply

        for bad in must_not_have:
            if bad.lower() in reply.lower():
                return "FAIL", f"금지어 포함: '{bad}'", reply

        for good in must_have:
            if good.lower() in reply.lower():
                return "PASS", "", reply

        return "FAIL", f"기대 키워드 없음: {must_have}", reply
    except Exception as e:
        return "ERR", str(e), ""

_DB_CFG = {"host": "127.0.0.1", "port": "3306", "user": "master", "password": "1234", "database": "smart_home"}
_c = _mc.connect(**_DB_CFG); _cur = _c.cursor()
_cur.execute("SELECT COALESCE(MAX(id), 0) FROM aircon_schedule"); _pre_sched_id = _cur.fetchone()[0]
_cur.close(); _c.close()

print(f"\n{'='*70}")
print(f"  chatbot 테스트 시작 — {datetime.now().strftime('%H:%M:%S')}  ({len(TESTS)}개)")
print(f"{'='*70}\n")

for i, (q, cat, must, must_not) in enumerate(TESTS, 1):
    status, reason, reply = test_one(q, cat, must, must_not)
    results[status].append((q, cat, reason, reply))
    icon = "✅" if status == "PASS" else ("❌" if status == "FAIL" else "⚠️")
    line = f"{icon} [{cat:8s}] {q}"
    if status != "PASS":
        line += f"\n         → {reason}"
        if reply and VERBOSE:
            line += f"\n         응답: {reply[:120]}"
    print(line)

# ─── 요약 ──────────────────────────────────────────────────────────────────
total = len(TESTS)
n_pass = len(results["PASS"])
n_fail = len(results["FAIL"])
n_err  = len(results["ERR"])
print(f"\n{'='*70}")
print(f"  결과: PASS {n_pass}/{total}  FAIL {n_fail}  ERR {n_err}  ({n_pass/total*100:.0f}%)")
print(f"{'='*70}\n")

if results["FAIL"] or results["ERR"]:
    print("─── FAIL/ERR 목록 (응답 미리보기) ───")
    for q, cat, reason, reply in results["FAIL"] + results["ERR"]:
        print(f"  [{cat}] {q}")
        print(f"    이유: {reason}")
        print(f"    응답: {reply[:150]}\n")

# 카테고리별 요약
from collections import defaultdict
cat_stats = defaultdict(lambda: [0, 0])
for q, cat, _, _ in results["PASS"]:   cat_stats[cat][0] += 1
for q, cat, _, _ in (results["FAIL"] + results["ERR"]): cat_stats[cat][1] += 1
print("─── 카테고리별 ───")
for cat in sorted(cat_stats):
    p, f = cat_stats[cat]
    total_c = p + f
    print(f"  {cat:10s}: {p}/{total_c} {'✅' if f == 0 else '❌'}")

