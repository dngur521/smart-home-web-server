def post(msg: str) -> tuple:
    try:
        r = requests.post(BASE_URL, json={"message": msg, "history": []}, timeout=90)
        if r.status_code != 200:
            return "ERR", f"HTTP {r.status_code}", ""
        reply = r.json().get("reply", "")
        return "OK", reply, ""
    except Exception as e:
        return "ERR", "", str(e)


_DB_CFG = {"host": "127.0.0.1", "port": "3306", "user": "master", "password": "1234", "database": "smart_home"}


def _pre_cleanup():
    c = mysql.connector.connect(**_DB_CFG)
    cur = c.cursor()
    cur.execute("SELECT COALESCE(MAX(id), 0) FROM aircon_schedule")
    mid = cur.fetchone()[0]
    cur.close(); c.close()
    return mid


def _post_cleanup(mid):
    c = mysql.connector.connect(**_DB_CFG)
    cur = c.cursor()
    cur.execute("DELETE FROM aircon_schedule WHERE id > %s", (mid,))
    deleted = cur.rowcount
    c.commit(); cur.close(); c.close()
    if deleted:
        print(f"\n[cleanup] 테스트 생성 예약 {deleted}건 삭제")


def run_tests(tests):
    results = {"PASS": [], "FAIL": [], "ERR": []}
    cat_stats = defaultdict(lambda: [0, 0])

    for i, (q, cat, must_have, must_not) in enumerate(tests, 1):
        status, reply, err = post(q)

        if status == "ERR":
            results["ERR"].append((q, cat, err, ""))
            cat_stats[cat][1] += 1
            if VERBOSE:
                print(f"⚠️  [{cat}] {q}\n    ERR: {err}")
            else:
                print(f"⚠️ ", end="", flush=True)
            time.sleep(0.15)
            continue

        # 판정
        fail_reasons = []
        for bad in must_not:
            if bad.lower() in reply.lower():
                fail_reasons.append(f"금지어 '{bad}' 포함")
        if not fail_reasons:
            matched = any(g.lower() in reply.lower() for g in must_have)
            if not matched and must_have:
                fail_reasons.append(f"기대어 없음: {must_have}")

        if fail_reasons:
            results["FAIL"].append((q, cat, " | ".join(fail_reasons), reply))
            cat_stats[cat][1] += 1
            print(f"❌", end="", flush=True)
        else:
            results["PASS"].append((q, cat, "", reply))
            cat_stats[cat][0] += 1
            print(f"✅", end="", flush=True)

        if i % 50 == 0:
            print(f" [{i}/{len(tests)}]")
        time.sleep(0.15)

    return results, cat_stats


def print_summary(results, cat_stats, total):
    n_pass = len(results["PASS"])
    n_fail = len(results["FAIL"])
    n_err  = len(results["ERR"])
    print(f"\n\n{'='*70}")
    print(f"  결과: PASS {n_pass}/{total}  FAIL {n_fail}  ERR {n_err}  ({n_pass/total*100:.1f}%)")
    print(f"{'='*70}")

    if results["FAIL"] or results["ERR"]:
        print("\n─── FAIL 목록 ───")
        for q, cat, reason, reply in results["FAIL"]:
            print(f"  [{cat}] {q}")
            print(f"    이유: {reason}")
            print(f"    응답: {reply[:120]}\n")
        for q, cat, err, _ in results["ERR"]:
            print(f"  [{cat}] {q}  ERR: {err}")

    print("\n─── 카테고리별 ───")
    for cat in sorted(cat_stats):
        p, f = cat_stats[cat]
        total_c = p + f
        bar = "✅" if f == 0 else "❌"
        print(f"  {cat:22s}: {p}/{total_c} {bar}")


